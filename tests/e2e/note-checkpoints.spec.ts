import {test,expect} from '@playwright/test';
import {createClient} from '@supabase/supabase-js';
import {createServerClient} from '@supabase/ssr';
import sharp from 'sharp';
import {readFile} from 'node:fs/promises';
import {unzipSync,strFromU8} from 'fflate';

test('첫 메모 → 재접속 → 두 번째 메모 → 보관 → 수정·충돌·ZIP 반출',async({page,baseURL})=>{
 page.on('pageerror',error=>console.log('Browser error:',error.message));
 page.on('response',response=>{
  const path=new URL(response.url()).pathname;
  if(path.startsWith('/api/')) console.log('API',response.request().method(),path.replace(/[0-9a-f-]{36}/g,':id'),response.status());
 });
 const url=process.env.NEXT_PUBLIC_SUPABASE_URL!;
 const key=process.env.NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY!;
 const admin=createClient(url,process.env.SUPABASE_SERVER_SECRET_KEY!,{auth:{persistSession:false,autoRefreshToken:false}});
 const email=`checkpoint-${crypto.randomUUID()}@example.test`,password=crypto.randomUUID()+'Aa1!';
 const created=await admin.auth.admin.createUser({email,password,email_confirm:true});
 expect(created.error).toBeNull();
 const userId=created.data.user!.id;
 try {
  const user=createClient(url,key,{auth:{persistSession:false,autoRefreshToken:false}});
  const signed=await user.auth.signInWithPassword({email,password});
  expect(signed.error).toBeNull();
  const cookies=new Map<string,string>();
  const server=createServerClient(url,key,{cookies:{getAll:()=>[],setAll:values=>values.forEach(v=>cookies.set(v.name,v.value))}});
  expect((await server.auth.setSession(signed.data.session!)).error).toBeNull();
  await page.context().addCookies([...cookies].map(([name,value])=>({name,value,url:baseURL!})));
  const original=await sharp({create:{width:4,height:3,channels:3,background:'#af0'}}).png().toBuffer();
  const headers={Origin:baseURL!};
  const reserved=await page.request.post('/api/uploads',{headers,data:{files:[{original_name:'checkpoint-synthetic.png',mime_type:'image/png',byte_size:original.length,client_request_id:crypto.randomUUID()}]}});
  expect(reserved.status(),await reserved.text()).toBe(201);
  const reservation=(await reserved.json()).reservations[0];
  expect((await user.storage.from('memory-assets').uploadToSignedUrl(reservation.path,reservation.token,original,{contentType:'image/png'})).error).toBeNull();
  const completed=await page.request.post(`/api/uploads/${reservation.id}/complete`,{headers});
  expect(completed.status(),await completed.text()).toBe(200);
  const id=reservation.id;
  await page.goto('/revisit');
  const editor=page.getByRole('textbox',{name:'기억 메모'});
  await expect(editor).toBeEnabled();
  await expect(page.getByRole('button',{name:'첫 번째 메모 남기기'})).toBeDisabled();
  await editor.fill('합성 첫 번째 메모');
  const firstResponse=page.waitForResponse(r=>r.url().endsWith(`/api/photos/${id}/note`)&&r.request().method()==='PUT');
  await page.getByRole('button',{name:'첫 번째 메모 남기기'}).click();
  const first=await firstResponse;
  expect(first.status()).toBe(200);
  expect(first.request().postDataJSON().note_stage).toBe('first');
  const firstPhoto=await first.json();
  expect(firstPhoto).toMatchObject({note_text:'합성 첫 번째 메모',second_note_text:'',second_note_at:null,preserved_at:null});
  expect(firstPhoto.first_note_at).toBeTruthy();
  await expect(editor).toHaveValue('');
  const firstList=await page.request.get('/api/photos?scope=preserved');
  expect((await firstList.json()).photos).toHaveLength(0);
  await page.reload();
  await expect(editor).toHaveValue('');
  await editor.fill('합성 두 번째 메모');
  const secondResponse=page.waitForResponse(r=>r.url().endsWith(`/api/photos/${id}/note`)&&r.request().method()==='PUT');
  await page.getByRole('button',{name:'두 번째 메모 남기기'}).click();
  const second=await secondResponse;
  expect(second.status()).toBe(200);
  expect(second.request().postDataJSON().note_stage).toBe('second');
  const secondPhoto=await second.json();
  expect(secondPhoto).toMatchObject({note_text:'합성 첫 번째 메모',second_note_text:'합성 두 번째 메모',first_note_at:firstPhoto.first_note_at});
  expect(secondPhoto.second_note_at).toBeTruthy();
  expect(secondPhoto.preserved_at).toBeTruthy();
  await expect(editor).toHaveValue('합성 두 번째 메모');
  await page.goto('/memories');
  await page.getByRole('button',{name:'합성 두 번째 메모',exact:true}).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.getByRole('button',{name:'수정',exact:true}).click();
  await page.getByRole('dialog').getByRole('textbox').fill('보관함에서 수정한 두 번째 메모');
  const viewerSaveResponse=page.waitForResponse(r=>r.url().endsWith(`/api/photos/${id}/note`)&&r.request().method()==='PUT');
  await page.getByRole('button',{name:'저장',exact:true}).click();
  const viewerSaved=await viewerSaveResponse;
  expect(viewerSaved.status()).toBe(200);
  expect((await viewerSaved.json()).second_note_text).toBe('보관함에서 수정한 두 번째 메모');
  await expect(page.getByRole('dialog').getByText('보관함에서 수정한 두 번째 메모',{exact:true})).toBeVisible();
  const [download]=await Promise.all([page.waitForEvent('download'),page.getByRole('button',{name:'사진과 메모 다운로드'}).click()]);
  const zip=unzipSync(await readFile((await download.path())!));
  expect(Buffer.from(zip['original.png']).equals(original)).toBe(true);
  expect(JSON.parse(strFromU8(zip['memory.json']))).toMatchObject({note_text:'합성 첫 번째 메모',first_note_at:firstPhoto.first_note_at,second_note_text:'보관함에서 수정한 두 번째 메모',second_note_at:secondPhoto.second_note_at,preserved_at:secondPhoto.preserved_at});
  const bulk=await page.request.get('/api/me/export/zip');
  expect(bulk.status()).toBe(200);
  const bulkZip=unzipSync(await bulk.body());
  expect(JSON.parse(strFromU8(bulkZip[`${id}/memory.json`])).second_note_text).toBe('보관함에서 수정한 두 번째 메모');
  await page.goto(`/photos/${id}/edit`);
  const edit=page.getByRole('textbox',{name:'메모',exact:true});
  await expect(edit).toHaveValue('보관함에서 수정한 두 번째 메모');
  await edit.fill('충돌 후 유지할 합성 초안');
  const current=await admin.from('photos').select('version').eq('id',id).single();
  const concurrent=await admin.rpc('save_note',{p_user_id:userId,p_photo_id:id,p_note_text:'다른 세션의 두 번째 메모',p_expected_version:current.data!.version,p_request_id:crypto.randomUUID(),p_note_stage:'second'});
  expect(concurrent.error).toBeNull();
  await page.getByRole('button',{name:'저장하기'}).click();
  await expect(page.getByText('다른 기기에서 저장된 내용이 있어요')).toBeVisible();
  await expect(edit).toHaveValue('충돌 후 유지할 합성 초안');
  await page.getByRole('button',{name:'내 입력으로 덮어쓰기'}).click();
  const retryResponse=page.waitForResponse(r=>r.url().endsWith(`/api/photos/${id}/note`)&&r.request().method()==='PUT');
  await page.getByRole('button',{name:'저장하기'}).click();
  expect((await retryResponse).status()).toBe(200);
  await page.waitForTimeout(1000);
  await page.goto('/revisit');
  await expect(editor).toHaveValue('충돌 후 유지할 합성 초안');
  await editor.fill('');
  const clearResponse=page.waitForResponse(r=>r.url().endsWith(`/api/photos/${id}/note`)&&r.request().method()==='PUT');
  await page.getByRole('button',{name:'메모 수정하기'}).click();
  expect((await clearResponse).status()).toBe(200);
  const final=await admin.from('photos').select('note_text,second_note_text,preserved_at,first_note_at,second_note_at').eq('id',id).single();
  expect(final.error).toBeNull();
  expect(final.data).toMatchObject({note_text:'합성 첫 번째 메모',second_note_text:'',preserved_at:secondPhoto.preserved_at,first_note_at:firstPhoto.first_note_at,second_note_at:secondPhoto.second_note_at});
  const latest=await page.request.get('/api/photos?scope=preserved');
  expect((await latest.json()).photos).toHaveLength(1);
 } finally {
  const photos=await admin.from('photos').select('original_key,thumbnail_key').eq('user_id',userId);
  expect(photos.error).toBeNull();
  const keys=(photos.data??[]).flatMap(p=>[p.original_key,p.thumbnail_key].filter(Boolean));
  if(keys.length) expect((await admin.storage.from('memory-assets').remove(keys)).error).toBeNull();
  for(const table of ['cleanup_jobs','events','photos','trials','profiles']) expect((await admin.from(table).delete().eq('user_id',userId)).error).toBeNull();
  expect((await admin.auth.admin.deleteUser(userId)).error).toBeNull();
 }
});
